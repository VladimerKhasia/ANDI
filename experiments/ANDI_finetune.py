MODEL_NAME = "unsloth/llama-3-8b-bnb-4bit"
SEED = 3407
BATCH_SIZE = 8
GRAD_ACCUM = 2
MAX_STEPS = 300

dataset = load_dataset("vicgalle/alpaca-gpt4", split="train")
dataset = dataset.train_test_split(test_size=200, seed=SEED)

def force_cleanup():
    gc.collect()
    torch.cuda.empty_cache()

def configure_optimizers(model, optimizer_cls, lr, weight_decay, **kwargs):
    """
    Splits parameters and passes extra kwargs (like betas) to the optimizer.
    """
    decay = []
    no_decay = []

    for name, param in model.named_parameters():
        if not param.requires_grad: continue
        if param.ndim < 2 or "bias" in name or "norm" in name:
            no_decay.append(param)
        else:
            decay.append(param)

    optim_groups = [
        {'params': decay, 'weight_decay': weight_decay},
        {'params': no_decay, 'weight_decay': 0.0}
    ]

    # Pass **kwargs (e.g., betas) to the optimizer constructor
    return optimizer_cls(optim_groups, lr=lr, **kwargs)

def run_experiment(run_name, optimizer_class, lr, custom_wd, lora_alpha=16, opt_kwargs=None):
    if opt_kwargs is None: opt_kwargs = {}

    print(f"\n> RUN: {run_name} | LR: {lr} | WD: {custom_wd} | Alpha: {lora_alpha}")

    # 1. Load Model
    model, tokenizer = FastLanguageModel.from_pretrained(
        model_name = MODEL_NAME, max_seq_length = 2048, dtype = None, load_in_4bit = True,
    )

    # 2. Setup LoRA with CUSTOM ALPHA
    model = FastLanguageModel.get_peft_model(
        model,
        r = 16,
        target_modules = ["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
        lora_alpha = lora_alpha,
        lora_dropout = 0,
        bias = "none",
        use_gradient_checkpointing = "unsloth",
        random_state = SEED,
    )

    # 3. Precision Cast
    for param in model.parameters():
        if param.requires_grad: param.data = param.data.float()

    tokenizer = get_chat_template(tokenizer, chat_template = "llama-3")
    def format_func(examples):
        texts = []
        for i, inp, out in zip(examples["instruction"], examples["input"], examples["output"]):
            msgs = [{"role": "user", "content": f"{i}\n{inp}"}, {"role": "assistant", "content": out}]
            texts.append(tokenizer.apply_chat_template(msgs, tokenize=False, add_generation_prompt=False))
        return {"text": texts}

    train_ds = dataset["train"].map(format_func, batched=True)
    eval_ds = dataset["test"].map(format_func, batched=True)

    # 4. Initialize Optimizer
    # We pass the class (e.g. torch.optim.AdamW or DMuon) and it gets configured
    custom_opt = configure_optimizers(model, optimizer_class, lr, custom_wd, **opt_kwargs)

    # 5. Trainer
    trainer = SFTTrainer(
        model = model, tokenizer = tokenizer, train_dataset = train_ds, eval_dataset = eval_ds,
        dataset_text_field = "text", max_seq_length = 2048, packing = False,
        optimizers = (custom_opt, None),
        args = SFTConfig(
            per_device_train_batch_size = BATCH_SIZE, gradient_accumulation_steps = GRAD_ACCUM,
            warmup_steps = 10, max_steps = MAX_STEPS, learning_rate = lr,
            fp16 = not torch.cuda.is_bf16_supported(), bf16 = torch.cuda.is_bf16_supported(),
            logging_steps = 10, optim = "sgd", weight_decay = 0.0,
            lr_scheduler_type = "cosine", seed = SEED, output_dir = f"outputs_{run_name}",
            report_to = "none", eval_strategy = "steps", eval_steps = 20,
        ),
    )

    trainer.train()

    # Extract Loss and Eval History only
    loss_data = []
    eval_data = []
    for log in trainer.state.log_history:
        if "loss" in log and "eval_loss" not in log:
            loss_data.append(log["loss"])
        elif "eval_loss" in log:
            eval_data.append(log["eval_loss"])

    del model, tokenizer, trainer, custom_opt
    force_cleanup()

    return loss_data, eval_data

